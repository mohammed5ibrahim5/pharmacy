export function getArticleBySlug(slug: string): HealthArticle | undefined {
  return healthArticles.find((a) => a.slug === slug);
}

export function getArticlesBySearchHint(hint: string): HealthArticle[] {
  const parts = hint.split(/\s+/).filter(Boolean);
  if (parts.length === 0) return [];
  return healthArticles.filter((a) =>
    parts.every((p) => `${a.title} ${a.excerpt} ${a.keywords.join(' ')}`.includes(p))
  );
}